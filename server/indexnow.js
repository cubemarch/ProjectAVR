/**
 * IndexNow: telling Bing a URL changed, instead of waiting to be crawled.
 *
 * Bing, Yandex, Seznam and Naver share one endpoint. You publish a key at a
 * fixed path on your own host, then POST a list of URLs with that key; serving
 * the file is what proves the submission came from someone who controls the
 * host. Google does not participate and has said so, so nothing here affects
 * Google ranking at all.
 *
 * It is here anyway, and the reason is narrower than SEO. **ChatGPT's web
 * results come from Bing**, and so do Copilot's. For a domain that cannot buy
 * search advertising, cannot be browsed by ChatGPT's own agent, and is mostly
 * invisible to crawlers that do not run JavaScript, a free push straight into
 * the index those answers are drawn from is the shortest path there is between
 * publishing something and an AI assistant being able to cite it.
 *
 * ## The key is not a secret
 *
 * It is served in plaintext at a public URL on purpose — that is the entire
 * verification mechanism. It is committed rather than threaded through the
 * environment because a value that is published by design gains nothing from
 * being configurable and loses the one property that matters: that the file
 * and the submission cannot disagree about what the key is. `test/seo.test.js`
 * pins that they match, because a key file that 404s makes every submission
 * fail with an error nobody is watching for.
 *
 * Rotating it is two edits — the constant here and the filename in `public/` —
 * and nothing else refers to it.
 *
 * ## Submission is manual
 *
 * There is no hook on boot. Restarts are not content changes, and the protocol
 * asks submitters not to resend URLs that have not changed; a server that
 * pinged on every deploy would be sending the same six addresses forever and
 * teaching the endpoint to ignore this host. Run `npm run indexnow` when
 * something has actually changed.
 */

const KEY = 'b22f51bdb55edfc48f2f7facc9105985';

/** The key, and the basename it must be published under. */
export const INDEXNOW_KEY = KEY;
export const INDEXNOW_KEY_FILE = `${KEY}.txt`;

const ENDPOINT = 'https://api.indexnow.org/indexnow';
const HOST = 'lustxr.com';

/**
 * Pull the addresses out of a sitemap.
 *
 * Deliberately a regex rather than an XML parser. The sitemap is generated by
 * this same codebase from a list of literals, so its shape is known, and
 * adding a parser dependency to read one tag out of a file we wrote ourselves
 * is a poor trade.
 */
export function sitemapLocs(xml) {
    return [...String(xml).matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].trim());
}

/**
 * Submit a list of URLs.
 *
 * Every URL has to be on `HOST` — the endpoint rejects the whole batch if any
 * one of them is not, which is a confusing failure to debug from the 422 it
 * answers with, so it is checked here where the message can say which.
 *
 * A 200 and a 202 both mean accepted. 429 means too many submissions and is
 * the expected answer to running this repeatedly with nothing changed.
 */
export async function submitUrls(urls, { fetchImpl = fetch } = {}) {
    if (!urls.length) throw new Error('nothing to submit');

    const foreign = urls.filter((u) => new URL(u).host !== HOST);
    if (foreign.length) {
        throw new Error(`not on ${HOST}: ${foreign.join(', ')}`);
    }

    const res = await fetchImpl(ENDPOINT, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json; charset=utf-8' },
        body: JSON.stringify({
            host: HOST,
            key: KEY,
            keyLocation: `https://${HOST}/${INDEXNOW_KEY_FILE}`,
            urlList: urls
        })
    });

    return { status: res.status, ok: res.status === 200 || res.status === 202 };
}

/* ------------------------------------------------------------------ cli -- */

if (process.argv[1] && process.argv[1].endsWith('indexnow.js')) {
    const sitemap = `https://${HOST}/sitemap.xml`;

    const xml = await fetch(sitemap).then((r) => {
        if (!r.ok) throw new Error(`${sitemap} answered ${r.status}`);
        return r.text();
    });

    const urls = sitemapLocs(xml);
    console.log(`[indexnow] ${urls.length} urls from ${sitemap}`);

    // Fail loudly rather than submitting a key the host does not serve: the
    // endpoint's own answer to that is a 403 that says nothing useful.
    const keyUrl = `https://${HOST}/${INDEXNOW_KEY_FILE}`;
    const served = await fetch(keyUrl).then((r) => (r.ok ? r.text() : null));
    if (served?.trim() !== KEY) {
        console.error(`[indexnow] ${keyUrl} does not serve the key — deploy first`);
        process.exit(1);
    }

    const { status, ok } = await submitUrls(urls);
    console.log(`[indexnow] ${ok ? 'accepted' : 'refused'} (${status})`);
    process.exit(ok ? 0 : 1);
}
